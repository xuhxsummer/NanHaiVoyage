CREATE TABLE player_cargo (user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, kind VARCHAR(16) NOT NULL CHECK (kind IN ('trade','beasts','herbs','fish','costPaid')), item_index INTEGER NOT NULL CHECK(item_index >= 0), qty INTEGER NOT NULL CHECK(qty >= 0), PRIMARY KEY(user_id,kind,item_index));
CREATE TABLE player_codex (user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, kind VARCHAR(16) NOT NULL CHECK(kind IN ('beastFound','herbFound')), item_index INTEGER NOT NULL CHECK(item_index >= 0), found BOOLEAN NOT NULL, PRIMARY KEY(user_id,kind,item_index));
CREATE TABLE player_market (user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, item_index INTEGER NOT NULL CHECK(item_index >= 0), price_offset INTEGER NOT NULL, PRIMARY KEY(user_id,item_index));
